-- Document library (Phase 1): procedures, SOPs, manuals, SDS, emergency
-- documents and forms — with versions, private files and read evidence.
--
-- What changes:
-- * documents          — one row per document: category, clearly-labelled
--   type (official / internal guide / draft), title, optional SOP number,
--   responsible owner and status (draft / published / archived).
-- * document_versions  — one row per version of a document. Versions are
--   APPEND-ONLY: a new version never overwrites the bytes or the row of a
--   previous one, so the exact file a technician read stays retrievable.
--   The file itself lives in the private "documents" Storage bucket; this
--   table only keeps storage_path + metadata.
-- * document_reads     — read confirmations, one per (version, member):
--   who confirmed reading WHICH version, and when. Evidence of reading,
--   never a claim of compliance verification.
-- * admin_audit_log    — its action list gains the document actions so every
--   administrative change to the library lands in the Phase 0 audit trail.
-- * storage bucket "documents" — created PRIVATE (public = false). Files
--   are uploaded and downloaded only by server routes after a permission
--   check; downloads use short-lived signed URLs. No document content is
--   ever committed to the git repository.
--
-- This migration is ADDITIVE ONLY: no table or column is dropped and no
-- existing row is touched. All new tables use the same server-only pattern
-- as the rest of the schema: RLS enabled, anon/authenticated revoked, and
-- an explicit deny policy as defense in depth.

create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  category text not null check (category in (
    'sop_greystar', 'procedimiento_interno', 'manual_fabricante',
    'sds', 'emergencia', 'formulario', 'otro'
  )),
  doc_type text not null default 'internal_guide' check (doc_type in (
    'official', 'internal_guide', 'draft'
  )),
  title text not null,
  sop_number text,
  owner_member_id bigint references public.members(id) on delete set null,
  status text not null default 'draft' check (status in (
    'draft', 'published', 'archived'
  )),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.document_versions (
  id bigint generated by default as identity primary key,
  document_id bigint not null references public.documents(id) on delete restrict,
  version_number integer not null check (version_number > 0),
  effective_date date,
  change_note text,
  storage_path text not null,
  file_name text not null,
  content_type text,
  file_size bigint,
  uploaded_by uuid references auth.users(id) on delete set null,
  uploaded_by_member_id bigint references public.members(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (document_id, version_number)
);

create table if not exists public.document_reads (
  id bigint generated by default as identity primary key,
  version_id bigint not null references public.document_versions(id) on delete restrict,
  member_id bigint not null references public.members(id) on delete restrict,
  user_id uuid references auth.users(id) on delete set null,
  read_at timestamptz not null default now(),
  unique (version_id, member_id)
);

create index if not exists documents_status_idx
  on public.documents (status);

create index if not exists documents_category_idx
  on public.documents (category);

create index if not exists document_versions_document_idx
  on public.document_versions (document_id, version_number desc);

create index if not exists document_reads_member_idx
  on public.document_reads (member_id);

alter table public.documents enable row level security;
alter table public.document_versions enable row level security;
alter table public.document_reads enable row level security;

-- Library data is read and written exclusively by authenticated server
-- routes that enforce the Phase 0/1 permission rules. Browser clients get
-- nothing directly.
revoke all on public.documents from anon, authenticated;
revoke all on public.document_versions from anon, authenticated;
revoke all on public.document_reads from anon, authenticated;

create policy "documents_server_only"
  on public.documents
  for all
  to anon, authenticated
  using (false)
  with check (false);

create policy "document_versions_server_only"
  on public.document_versions
  for all
  to anon, authenticated
  using (false)
  with check (false);

create policy "document_reads_server_only"
  on public.document_reads
  for all
  to anon, authenticated
  using (false)
  with check (false);

-- Administrative actions on documents join the Phase 0 audit trail.
alter table public.admin_audit_log
  drop constraint if exists admin_audit_log_action_check;

alter table public.admin_audit_log
  add constraint admin_audit_log_action_check
  check (action in (
    'approve_member', 'reject_member', 'suspend_member', 'revoke_member',
    'add_member', 'bootstrap_admin',
    'create_document', 'update_document', 'publish_document',
    'archive_document', 'add_document_version'
  ));

-- Private file storage for document versions. public = false means there is
-- no anonymous URL for any file: the server mints a short-lived signed URL
-- only after checking the requester's permissions.
insert into storage.buckets (id, name, public)
values ('documents', 'documents', false)
on conflict (id) do nothing;

-- Defense in depth: browser roles get no direct object access at all. The
-- application only ever touches objects through the server (service role)
-- and hands out signed URLs after a permission check.
create policy "documents_bucket_server_only"
  on storage.objects
  for all
  to anon, authenticated
  using (false)
  with check (false);
