-- Access model v2 (Phase 0): separate the job title from permissions.
--
-- What changes:
-- * members.job_title  — free-text "Posición / Job Title". Informational
--   only; it is NEVER read by any authorization check. Writing "Admin",
--   "Manager" or "Supervisor" in it grants nothing.
-- * members.is_admin   — the ONLY source of administrative privilege in the
--   app. Defaults to false for every row, existing and new. This migration
--   does NOT set it for anyone. It is granted exclusively by the manual,
--   owner-authorized script docs/admin-bootstrap.sql, which Jose Suarez
--   runs himself after confirming the exact admin account.
-- * approval_status gains 'rejected', 'suspended' and 'revoked'. Every new
--   account starts as 'pending' and cannot read property data until the
--   administrator approves it.
-- * admin_audit_log    — append-only record of every administrative action
--   (actor, action, target, detail, timestamp). Same server-only RLS
--   pattern as the rest of the schema: anon/authenticated are denied and
--   all access goes through authenticated server routes.
-- * work_orders gains updated_by / closed_by / closed_at so every change
--   and closure is attributable to a user with a timestamp. Closing a work
--   order never deletes it.
--
-- This migration is ADDITIVE ONLY: no table or column is dropped, no column
-- is retyped, and no existing row loses data. The legacy members.role and
-- members.requested_role columns are kept for historical reference; the
-- application no longer reads them for authorization.

alter table public.members
  add column if not exists job_title text;

alter table public.members
  add column if not exists is_admin boolean not null default false;

alter table public.members
  drop constraint if exists members_approval_status_check;

alter table public.members
  add constraint members_approval_status_check
  check (approval_status in ('unregistered', 'pending', 'approved', 'rejected', 'suspended', 'revoked'));

-- Display-only backfill: existing members keep a readable job title derived
-- from their legacy role. This grants no permission of any kind.
update public.members
set job_title = case role
  when 'manager' then 'Manager'
  when 'service_supervisor' then 'Service Supervisor'
  else 'Technician'
end
where job_title is null;

create index if not exists members_approval_status_idx
  on public.members (approval_status);

create index if not exists members_is_admin_idx
  on public.members (is_admin)
  where is_admin;

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_member_id bigint references public.members(id) on delete set null,
  actor_email text not null,
  action text not null check (action in (
    'approve_member', 'reject_member', 'suspend_member', 'revoke_member',
    'add_member', 'bootstrap_admin'
  )),
  target_member_id bigint references public.members(id) on delete set null,
  target_email text,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_log_created_at_idx
  on public.admin_audit_log (created_at desc);

create index if not exists admin_audit_log_target_idx
  on public.admin_audit_log (target_member_id);

alter table public.admin_audit_log enable row level security;

-- All administrative history is read and written exclusively by server
-- routes acting for the verified administrator. Browser clients get nothing.
revoke all on public.admin_audit_log from anon, authenticated;

create policy "admin_audit_log_server_only"
  on public.admin_audit_log
  for all
  to anon, authenticated
  using (false)
  with check (false);

alter table public.work_orders
  add column if not exists updated_by uuid references auth.users(id) on delete set null;

alter table public.work_orders
  add column if not exists closed_by uuid references auth.users(id) on delete set null;

alter table public.work_orders
  add column if not exists closed_at timestamptz;
