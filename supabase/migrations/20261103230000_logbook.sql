-- Property logbook (Phase 2): the central register of property events —
-- leaks, equipment failures, emergency calls, damage, vendor visits,
-- inspections and repairs — with case chains, comments, private evidence
-- attachments, an append-only history and in-app notifications.
--
-- What changes:
-- * log_folio_counters — per-year counter used by the server to mint the
--   human-readable folio of each event (BIT-2026-0001). The increment runs
--   inside public.next_log_folio_number() so two simultaneous creations
--   can never receive the same folio.
-- * log_events         — one row per event: readable folio, type, the
--   event datetime (occurred_at) kept SEPARATE from the registration
--   timestamp (created_at), reporter, building / unit / area / equipment
--   (free text until the assets module lands in Phase 3), description,
--   findings, actions taken, responsible member, priority, follow-up
--   date, status (open / in_progress / pending / closed), final result,
--   verifier + verification timestamp, and the official work-order
--   reference in Greystar's system (free text, optional). Closing never
--   deletes: closed_by / closed_at record who closed it and when.
-- * log_event_links    — relationships between events of the same case
--   (leak → inspection → roofer visit → report → interior repair →
--   verification). One row per link; the chain is traversed in BOTH
--   directions when a case is viewed. Links are never removed through
--   the app: a mistaken link stays visible in the trail.
-- * log_comments       — comments per event with author and timestamp.
--   Comments are never edited or deleted through the app; a correction
--   is a new comment.
-- * log_history        — APPEND-ONLY trail per event (creation, status
--   changes, assignments, priority / follow-up changes, detail edits,
--   closure, reopening, verification, comments, attachments, links) with
--   actor and timestamp. Only the server inserts rows; the API exposes
--   no update or delete path for this table.
-- * log_attachments    — metadata for evidence files. The bytes live in
--   the private "logbook" Storage bucket; this table only keeps
--   storage_path + metadata.
-- * notifications      — stored in-app notifications (assignment and
--   comment on your events). Overdue follow-ups are NOT stored: they
--   are computed at read time from follow_up_date, so they never go
--   stale. No email or push in this phase.
-- * storage bucket "logbook" — created PRIVATE (public = false). Files
--   are uploaded and downloaded only by server routes after a permission
--   check; downloads use short-lived signed URLs. No attachment content
--   is ever committed to the git repository.
--
-- Permissions (access model v2, enforced in server routes AND here):
-- approved accounts operate the logbook with identical permissions;
-- unapproved accounts get nothing. This migration only sets the
-- database side: RLS enabled, all grants to anon/authenticated revoked,
-- and an explicit deny policy per table as defense in depth — the same
-- server-only pattern as Phases 0 and 1.
--
-- This migration is ADDITIVE ONLY: no table or column is dropped and no
-- existing row is touched.

create table if not exists public.log_folio_counters (
  year integer primary key,
  last_number integer not null default 0
);

-- Atomic folio increment. Runs inside one statement (insert … on conflict
-- … returning) so concurrent event creations cannot collide.
create or replace function public.next_log_folio_number(p_year integer)
returns integer
language plpgsql
as $$
declare
  v_next integer;
begin
  insert into public.log_folio_counters (year, last_number)
  values (p_year, 1)
  on conflict (year) do update
    set last_number = public.log_folio_counters.last_number + 1
  returning last_number into v_next;
  return v_next;
end;
$$;

-- Only the server (service role, used by the API routes) may mint folios.
revoke all on function public.next_log_folio_number(integer)
  from public, anon, authenticated;

create table if not exists public.log_events (
  id bigint generated by default as identity primary key,
  folio text not null unique,
  event_type text not null check (event_type in (
    'leak', 'equipment_failure', 'emergency_call', 'damage',
    'vendor_visit', 'inspection', 'repair', 'other'
  )),
  occurred_at timestamptz not null,
  reported_by_member_id bigint references public.members(id) on delete set null,
  reported_by_user_id uuid references auth.users(id) on delete set null,
  building text,
  unit text,
  area text,
  equipment text,
  description text not null,
  findings text,
  actions_taken text,
  responsible_member_id bigint references public.members(id) on delete set null,
  priority text not null default 'medium' check (priority in (
    'low', 'medium', 'high', 'emergency'
  )),
  follow_up_date date,
  status text not null default 'open' check (status in (
    'open', 'in_progress', 'pending', 'closed'
  )),
  final_result text,
  verified_by_member_id bigint references public.members(id) on delete set null,
  verified_at timestamptz,
  official_wo_ref text,
  closed_by_member_id bigint references public.members(id) on delete set null,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.log_event_links (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.log_events(id) on delete restrict,
  related_event_id bigint not null references public.log_events(id) on delete restrict,
  relation text not null default 'related' check (relation in (
    'related', 'inspection', 'vendor_visit', 'report', 'repair',
    'verification', 'follow_up'
  )),
  created_by_member_id bigint references public.members(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (event_id, related_event_id),
  check (event_id <> related_event_id)
);

create table if not exists public.log_comments (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.log_events(id) on delete restrict,
  author_member_id bigint references public.members(id) on delete set null,
  author_user_id uuid references auth.users(id) on delete set null,
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.log_history (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.log_events(id) on delete restrict,
  actor_member_id bigint references public.members(id) on delete set null,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_email text not null,
  action text not null check (action in (
    'created', 'details_updated', 'status_changed', 'assigned',
    'priority_changed', 'follow_up_changed', 'closed', 'reopened',
    'verified', 'comment_added', 'attachment_added', 'linked'
  )),
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.log_attachments (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.log_events(id) on delete restrict,
  storage_path text not null,
  file_name text not null,
  content_type text,
  file_size bigint,
  uploaded_by_member_id bigint references public.members(id) on delete set null,
  uploaded_by_user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_member_id bigint not null references public.members(id) on delete restrict,
  type text not null check (type in ('log_assigned', 'log_comment')),
  event_id bigint references public.log_events(id) on delete restrict,
  actor_member_id bigint references public.members(id) on delete set null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

