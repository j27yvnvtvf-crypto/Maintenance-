-- Private file storage for logbook evidence. public = false means there
-- is no anonymous URL for any file: the server mints a short-lived signed
-- URL only after checking the requester's permissions.
insert into storage.buckets (id, name, public)
values ('logbook', 'logbook', false)
on conflict (id) do nothing;

-- Defense in depth: browser roles get no direct object access at all. The
-- application only ever touches objects through the server (service role)
-- and hands out signed URLs after a permission check.
create policy "logbook_bucket_server_only"
  on storage.objects
  for all
  to anon, authenticated
  using (false)
  with check (false);
